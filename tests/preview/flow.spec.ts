import { test, expect } from '@playwright/test'

test('isolated preview completes customer checkout, cashier POS simulation and admin reporting without real API requests', async ({ page, request }, info) => {
  const errors: string[] = [], apiHits: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (new URL(request.url()).pathname.startsWith('/api/') || request.url().includes('supabase.co')) apiHits.push(request.url()) })
  await page.route('https://fonts.googleapis.com/**', route => route.fulfill({ body: '', contentType: 'text/css' }))
  await page.goto('/menu')
  await expect(page.getByRole('button', { name: /PREVIEW UI/ })).toBeVisible()
  await page.getByRole('link', { name: 'Tambah Udang Asam Manis + Nasi', exact: true }).click()
  await page.getByRole('button', { name: /Tambah ke Keranjang/ }).click()
  await page.goto('/checkout')
  await page.getByLabel('Nama', { exact: false }).fill('Pelanggan Demo Browser')
  await page.getByRole('button', { name: /Pesan Sekarang/ }).click()
  await expect(page).toHaveURL(/\/order\/[a-f0-9-]+/)
  const id = new URL(page.url()).pathname.split('/').at(-1)!
  await expect(page.getByText('DEMO004', { exact: true })).toBeVisible()
  await page.screenshot({ path: info.outputPath('customer-order.png'), fullPage: true })
  await page.goto('/cashier')
  await page.getByRole('combobox', { name: 'Pilih kasir', exact: true }).selectOption({ label: 'Kasir Raka Contoh' })
  await page.getByLabel('PIN kasir', { exact: true }).fill('123456')
  await page.getByRole('button', { name: 'Masuk ke Kasir', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Dashboard Kasir' })).toBeVisible()
  await page.getByRole('button', { name: 'Lihat pesanan DEMO004', exact: true }).click()
  await page.getByRole('button', { name: 'Cek menu / revisi', exact: true }).click()
  await page.getByRole('button', { name: 'Menu tersedia dan pelanggan setuju — Simpan', exact: true }).click()
  page.on('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Tangani pesanan ini', exact: true }).click()
  await page.getByLabel('Semua menu sudah dimasukkan ke aplikasi kasir', { exact: true }).check()
  await page.getByLabel('Pembayaran pelanggan sudah selesai di aplikasi kasir', { exact: true }).check()
  await page.getByRole('button', { name: 'Sudah masuk aplikasi kasir', exact: true }).click()
  await page.screenshot({ path: info.outputPath('cashier.png'), fullPage: true })
  await page.getByRole('button', { name: 'Keluar', exact: true }).click()
  await page.goto('/admin/login')
  await page.getByLabel('Username atau email', { exact: true }).fill('owner.demo')
  await page.getByLabel('Password', { exact: true }).fill('preview123')
  await page.getByRole('button', { name: 'Masuk', exact: true }).click()
  await expect(page.getByTestId('dashboard-revenue')).toBeVisible()
  await page.screenshot({ path: info.outputPath('admin.png'), fullPage: true })
  await page.goto('/admin/reports')
  await expect(page.getByRole('link', { name: 'Lihat pesanan', exact: true })).toHaveCount(1)
  await page.goto('/admin/products')
  await expect(page.getByRole('heading', { name: 'Produk', exact: true })).toBeVisible()
  await page.goto('/order/' + id)
  await expect(page.getByText('DEMO004', { exact: true })).toBeVisible()
  expect(apiHits).toEqual([])
  expect(errors).toEqual([])
  const blocked = await request.get('/api/core/menu')
  expect(blocked.status()).toBe(503)
})
